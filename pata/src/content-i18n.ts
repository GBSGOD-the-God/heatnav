/** Fold the translations above into a Bi that only has hi/en. */
export function localiseBi<T extends { hi: string; en: string }>(b: T): T {
  const extra = CONTENT[b.en];
  return extra ? { ...extra, ...b } : b;
}

/** The same for a list of paragraphs: each paragraph is looked up on its own,
 *  so a topic whose material is half translated still shows what it has. */
export function localiseList(b: { hi: string[]; en: string[] }): Record<string, string[]> {
  const out: Record<string, string[]> = { ...b };
  const langs = new Set<string>();
  for (const para of b.en) for (const l of Object.keys(CONTENT[para] ?? {})) langs.add(l);
  for (const l of langs) {
    const lines = b.en.map((para, i) => CONTENT[para]?.[l as Lang] ?? b.en[i]);
    // Only offer a language if we actually have every paragraph in it —
    // half a lesson in Malayalam and half in English is worse than English.
    if (lines.every((line, i) => line !== b.en[i])) out[l] = lines;
  }
  return out;
}

