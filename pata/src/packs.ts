// Student-side content in all 12 languages (C7), bundled so it works with the
// network off. Two parts:
//   1. UI strings for the Home screen.
//   2. A concept pack: when OCR recognises a known school topic on the
//      photographed page, we can explain it in the child's own language
//      without any network call.
// Anything not in the pack still works — the page is read aloud from the OCR
// text in the child's script, which is the part a struggling reader needs most.

