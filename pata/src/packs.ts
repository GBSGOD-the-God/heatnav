/** Find a bundled concept for OCR'd page text. Returns null when unknown —
 *  the caller then reads the page aloud instead, which still works. */
export function matchConcept(text: string): ConceptPack | null {
  const low = text.toLowerCase();
  for (const c of CONCEPTS) {
    if (c.triggers.some((t) => low.includes(t.toLowerCase()))) return c;
  }
  return null;
}
